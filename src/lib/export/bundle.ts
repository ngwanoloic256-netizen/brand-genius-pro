"use client";

import { zip } from "fflate";
import { buildBrandGuidePdf } from "./pdf";
import { inlineExternalImages } from "./inline-images";
import { generateFlyers } from "../ai/flyer";
import { formatCmyk, formatRgb } from "../color";
import type { BrandGuide } from "../types";

/**
 * The whole identity as one download.
 *
 * Everything here was already reachable, but only one button at a time: five
 * logo variants, each with its own SVG and PNG, plus the mockups, the flyers
 * and the PDF — a dozen clicks to leave with the thing you paid for. This packs
 * the same artwork into a single archive, laid out the way a designer expects
 * to receive a hand-off.
 *
 * Vector stays vector. PNGs are rendered alongside the SVGs only because the
 * people who receive a brand kit are not all running design software.
 */

export interface BundleProgress {
  /** What is being produced right now, for the button's label. */
  step: string;
  /** 0-1, for a progress bar. */
  ratio: number;
}

type Files = Record<string, Uint8Array>;

const encoder = new TextEncoder();

function put(files: Files, path: string, contents: string | Uint8Array) {
  files[path] = typeof contents === "string" ? encoder.encode(contents) : contents;
}

function withXmlDeclaration(svg: string): string {
  return svg.startsWith("<?xml")
    ? svg
    : `<?xml version="1.0" encoding="UTF-8"?>\n${svg}`;
}

/** Reads the drawing size off the SVG so the raster keeps its proportions. */
function intrinsicSize(svg: string): { width: number; height: number } {
  const viewBox = svg.match(/viewBox\s*=\s*["']([^"']+)["']/i);
  if (viewBox) {
    const parts = viewBox[1].trim().split(/[\s,]+/).map(Number);
    if (parts.length === 4 && parts[2] > 0 && parts[3] > 0) {
      return { width: parts[2], height: parts[3] };
    }
  }
  return { width: 512, height: 512 };
}

/**
 * Rasterises an SVG in the browser.
 *
 * External references are inlined first: an SVG loaded through `new Image()`
 * cannot fetch anything, so a mockup's photographic backplate would otherwise
 * rasterise blank.
 */
async function pngBytes(svg: string, scale: number): Promise<Uint8Array | null> {
  try {
    const { width, height } = intrinsicSize(svg);
    const source = await inlineExternalImages(svg);
    const url = URL.createObjectURL(
      new Blob([source], { type: "image/svg+xml;charset=utf-8" }),
    );

    try {
      const image = await new Promise<HTMLImageElement>((resolve, reject) => {
        const img = new Image();
        img.onload = () => resolve(img);
        img.onerror = () => reject(new Error("raster failed"));
        img.src = url;
      });

      const canvas = document.createElement("canvas");
      canvas.width = Math.max(1, Math.round(width * scale));
      canvas.height = Math.max(1, Math.round(height * scale));
      const ctx = canvas.getContext("2d");
      if (!ctx) return null;
      // No fillRect: leaving the canvas untouched is what preserves alpha.
      ctx.drawImage(image, 0, 0, canvas.width, canvas.height);

      const blob = await new Promise<Blob | null>((resolve) =>
        canvas.toBlob(resolve, "image/png"),
      );
      if (!blob) return null;
      return new Uint8Array(await blob.arrayBuffer());
    } finally {
      URL.revokeObjectURL(url);
    }
  } catch {
    // One unrenderable scene must not cost the whole archive.
    return null;
  }
}

/** CSS custom properties, ready to paste into a stylesheet. */
function tokensCss(guide: BrandGuide): string {
  const lines = [
    "/* Generated by BRAND GENIUS */",
    ":root {",
    ...guide.palette.map(
      (s) => `  --brand-${slugify(s.name)}: ${s.hex}; /* ${s.role} */`,
    ),
    "",
    ...Object.entries(guide.primaryScale).map(
      ([step, hex]) => `  --brand-primary-${step}: ${hex};`,
    ),
    "",
    ...guide.typography.map(
      (t) => `  --brand-font-${t.role}: ${t.stack};`,
    ),
    "}",
    "",
  ];
  return lines.join("\n");
}

/** The same values as data, for anyone wiring this into a design system. */
function tokensJson(guide: BrandGuide): string {
  return JSON.stringify(
    {
      name: guide.brief.name,
      generatedAt: guide.generatedAt,
      artDirection: {
        id: guide.strategy.artDirection.id,
        name: guide.strategy.artDirection.name,
      },
      palette: guide.palette.map((s) => ({
        name: s.name,
        role: s.role,
        hex: s.hex,
        rgb: formatRgb(s.rgb),
        cmyk: formatCmyk(s.cmyk),
        onColor: s.onColor,
      })),
      primaryScale: guide.primaryScale,
      typography: guide.typography.map((t) => ({
        role: t.role,
        family: t.family,
        stack: t.stack,
        weights: t.weights,
        sizePx: t.sizePx,
        lineHeight: t.lineHeight,
        letterSpacingEm: t.letterSpacingEm,
        googleFonts: t.googleFontsHref,
      })),
      logoUsage: guide.logoUsage,
      voice: guide.strategy.voice,
    },
    null,
    2,
  );
}

function readme(guide: BrandGuide): string {
  const name = guide.brief.name;
  return `${name} — brand kit
${"=".repeat(name.length + 13)}

Generated by BRAND GENIUS on ${new Date(guide.generatedAt).toLocaleDateString("en-GB", { day: "numeric", month: "long", year: "numeric" })}.
Art direction: ${guide.strategy.artDirection.name}

WHAT IS IN HERE

  ${slugify(name)}-brand-guide.pdf   The full guide, with the brand's own typefaces embedded.

  logo/svg/     Vector masters. Use these for anything printed or resized.
  logo/png/     4x rasters on a transparent background, for slides and docs.
  mockups/      The identity applied to real surfaces, as vector.
  flyers/       Print-ready at true size, 3mm bleed included.
  tokens.css    Custom properties, ready to paste into a stylesheet.
  tokens.json   The same values as data.

WHICH LOGO TO USE

${guide.logo.map((v) => `  ${v.id.padEnd(12)} ${v.usage}`).join("\n")}

  Clear space : ${guide.logoUsage.clearSpaceRatio}x the mark's height on every side.
  Minimum size: ${guide.logoUsage.minWidthPx}px on screen, ${guide.logoUsage.minWidthMm}mm in print.

FONTS

${guide.typography.map((t) => `  ${t.role.padEnd(9)} ${t.family}${t.googleFontsHref ? `\n            ${t.googleFontsHref}` : ""}`).join("\n")}
`;
}

function slugify(name: string): string {
  return (
    name
      .toLowerCase()
      .normalize("NFD")
      .replace(/[̀-ͯ]/g, "")
      .replace(/[^a-z0-9]+/g, "-")
      .replace(/^-|-$/g, "") || "brand"
  );
}

/**
 * Builds the archive.
 *
 * `onProgress` is reported per stage rather than per file: the PDF dominates
 * the wall clock, so a byte-accurate bar would sit at zero and then jump.
 */
export async function downloadBrandKit(
  guide: BrandGuide,
  onProgress?: (progress: BundleProgress) => void,
): Promise<void> {
  const name = slugify(guide.brief.name);
  const files: Files = {};
  const report = (step: string, ratio: number) => onProgress?.({ step, ratio });

  report("Building the PDF", 0.05);
  const pdf = await buildBrandGuidePdf(guide);
  put(files, `${name}-brand-guide.pdf`, new Uint8Array(await pdf.arrayBuffer()));

  report("Packing the vectors", 0.45);
  for (const variant of guide.logo) {
    put(
      files,
      `logo/svg/${name}-${variant.id}.svg`,
      withXmlDeclaration(variant.svg),
    );
  }
  put(files, `logo/${name}-mark.svg`, withXmlDeclaration(guide.mark.markup));

  for (const mockup of guide.mockups) {
    put(files, `mockups/${mockup.id}.svg`, withXmlDeclaration(mockup.svg));
  }

  let flyers: ReturnType<typeof generateFlyers> = [];
  try {
    flyers = generateFlyers(guide, { formats: ["a6", "a5", "dl", "a4"] });
  } catch {
    flyers = [];
  }
  for (const flyer of flyers) {
    put(
      files,
      `flyers/${name}-${flyer.format.id}.svg`,
      withXmlDeclaration(flyer.svg),
    );
  }

  report("Rendering PNGs", 0.6);
  for (const variant of guide.logo) {
    const bytes = await pngBytes(variant.svg, 4);
    if (bytes) put(files, `logo/png/${name}-${variant.id}@4x.png`, bytes);
  }

  report("Writing the tokens", 0.9);
  put(files, "tokens.css", tokensCss(guide));
  put(files, "tokens.json", tokensJson(guide));
  put(files, "README.txt", readme(guide));

  report("Compressing", 0.95);
  const archive = await new Promise<Uint8Array>((resolve, reject) => {
    zip(files, { level: 6 }, (err, data) =>
      err ? reject(err) : resolve(data),
    );
  });

  const blob = new Blob([archive as BlobPart], { type: "application/zip" });
  const url = URL.createObjectURL(blob);
  const link = document.createElement("a");
  link.href = url;
  link.download = `${name}-brand-kit.zip`;
  document.body.append(link);
  link.click();
  link.remove();
  requestAnimationFrame(() => URL.revokeObjectURL(url));

  report("Done", 1);
}
